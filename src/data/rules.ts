export function facility(b: Building) {
  const l = b.level ?? 0,
    d = BLOCKS[b.kind],
    o = OPERATION[b.kind];
  return {
    ...d,
    mass: d.mass * (1 + 0.2 * l),
    capacity: Math.floor(d.capacity * (1 + 0.4 * l)),
    power: d.power * (1 + 0.5 * l),
    demand: d.demand * (1 + 0.3 * l),
    lift: PHYSICAL[b.kind].lift * (1 + 0.35 * l),
    height: PHYSICAL[b.kind].height * (1 + 0.15 * l),
    jobs: o.jobs * (1 + 0.2 * l),
    food: o.food * (1 + 0.5 * l),
    materials: o.materials * (1 + 0.5 * l),
    aether: o.aether * (1 + 0.5 * l),
    income: o.income * (1 + 0.4 * l),
    upkeep: o.upkeep * (1 + 0.35 * l),
  };
}
