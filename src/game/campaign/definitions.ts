export const t = (ko: string, en: string): LocalText => ({ ko, en });
const goal = (
  id: Metric,
  ko: string,
  en: string,
  target: number,
  max = false,
  once = false,
): Goal => ({ id, text: t(ko, en), metric: id, target, max, once });
