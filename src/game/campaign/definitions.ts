const seedStage = (
  id: number,
  title: LocalText,
  type: Stage['type'],
  source: Stage['source'],
  layout: string,
  goals: Goal[],
  story: LocalText,
  patch: Partial<Stage> = {},
): Stage => ({
  id,
  chapter: Math.ceil(id / 5),
  title,
  type,
  source,
  layout,
  goals,
  story,
  seed: 2478 + id * 131,
  resources: 600,
  food: id >= 4,
  structure: id > 1,
  fall: id > 1,
  allowed: available(id),
  script: available(id),
  hold: id === 1 ? 0 : 10,
  optional: [stable(90), goal('collapse', '추가 붕괴 없음', 'No additional collapse', 0, true)],
  speaker: id <= 3 ? 'elena' : id <= 5 ? 'maya' : id <= 10 ? 'elena' : 'maya',
  next: id < 30 ? id + 1 : undefined,
  xp: 100 + id * 10,
  ...patch,
});
